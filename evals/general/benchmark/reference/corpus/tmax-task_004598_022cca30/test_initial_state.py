import os
import pytest

def test_requests_bin_exists():
    path = "/home/user/requests.bin"
    assert os.path.exists(path), f"File {path} is missing. It should have been generated by the setup script."
    assert os.path.isfile(path), f"Path {path} exists but is not a file."

def test_expected_results_exists():
    path = "/home/user/expected_results.txt"
    assert os.path.exists(path), f"File {path} is missing. It should have been generated by the setup script."
    assert os.path.isfile(path), f"Path {path} exists but is not a file."

def test_student_files_not_exist():
    audit_c = "/home/user/audit.c"
    makefile = "/home/user/Makefile"
    assert not os.path.exists(audit_c), f"File {audit_c} should not exist before the student starts."
    assert not os.path.exists(makefile), f"File {makefile} should not exist before the student starts."