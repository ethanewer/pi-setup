def test_cmake_builds():
    """Verify CMake can build the project."""
    # Create temporary build directory
    with tempfile.TemporaryDirectory() as build_dir:
        # Configure with CMake
        configure_cmd = [
            'cmake',
            '-S', '/app',
            '-B', build_dir,
            '-DCMAKE_BUILD_TYPE=Release'
        ]
        
        result = subprocess.run(configure_cmd, capture_output=True, text=True)
        assert result.returncode == 0, f"CMake configure failed: {result.stderr}"
        
        # Build the project
        build_cmd = ['cmake', '--build', build_dir, '--config', 'Release']
        result = subprocess.run(build_cmd, capture_output=True, text=True)
        assert result.returncode == 0, f"CMake build failed: {result.stderr}"
        
        # Check executable was created
        executable = os.path.join(build_dir, 'project_gamma')
        if os.name == 'nt':  # Windows
            executable += '.exe'
        assert os.path.exists(executable), f"Executable not found: {executable}"

