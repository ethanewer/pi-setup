def test_legacy_compatibility():
    """Verify CMake build produces similar flags to legacy script."""
    # Read legacy compiler flags from script
    with open('/app/legacy_build.sh', 'r') as f:
        legacy_script = f.read()
    
    # Extract C++ standard
    std_match = re.search(r'STD_VERSION="([^"]+)"', legacy_script)
    assert std_match, "Could not find STD_VERSION in legacy script"
    expected_std = std_match.group(1)
    
    # Check CMakeLists.txt sets the same standard
    with open('/app/CMakeLists.txt', 'r') as f:
        cmake_content = f.read()
    
    assert f'set(CMAKE_CXX_STANDARD {expected_std[-2:]}' in cmake_content or \
           f'cxx_std_{expected_std[-2:]}' in cmake_content, \
           f"CMake doesn't set C++{expected_std[-2:]} standard"
    
    # Check for both debug and release configurations
    assert 'CMAKE_BUILD_TYPE' in cmake_content or 'CMAKE_CONFIGURATION_TYPES' in cmake_content, \
           "CMake doesn't handle build types"

