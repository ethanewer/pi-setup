/* ballast-berm hidden case: PSA CCM*-no-tag decrypt of short messages.
 *
 * Authored for this task; not part of the upstream tree. The vectors below
 * were produced with the project's own CCM* no-tag primitive
 * (mbedtls_ccm_star_encrypt_and_tag with a zero-length tag) at the fixed
 * upstream build, whose output was cross-checked byte-for-byte against the
 * NIST DVPT AES-128 #15 known-answer test, then driven back through the
 * PUBLIC PSA API under test (psa_cipher_decrypt). The ciphertext byte
 * lengths chosen (1, 4, 5, 8, 15, 16, ... and AES-256 keys) differ from
 * every input the upstream regression tests exercise.
 *
 * Each vector's input to psa_cipher_decrypt is the 13-byte nonce followed
 * by the given ciphertext. Every one of these messages is valid: the only
 * length requirement CCM* has is that the input is at least as long as the
 * nonce it is given. A decrypt that returns anything other than PSA_SUCCESS
 * and the exact plaintext below fails the case.
 */
#include <stdio.h>
