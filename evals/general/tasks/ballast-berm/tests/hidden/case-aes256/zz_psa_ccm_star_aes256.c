typedef struct {
    int key_len;               /* 16 = AES-128, 32 = AES-256 */
    int ct_len;                /* ciphertext length in bytes */
    unsigned char key[32];
    unsigned char nonce[13];
    unsigned char ct[64];
    unsigned char pt[64];
} Vector;

typedef struct {
    const char *name;
    Vector v;
} Case;

