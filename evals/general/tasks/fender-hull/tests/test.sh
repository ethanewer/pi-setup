#!/bin/bash
# Verifier for fender-hull: an upstream-clone debugging task on
# cure53/DOMPurify (upstream issue #1560).
#
# The agent must fix, in the real checkout at /app/src, a real upstream bug:
# in-place sanitize of a live subtree aborts part-way through (before the
# fail-closed barrier) when the root element's document-owner lookup is
# intercepted — a form element whose shadowed property read hands the sanitizer
# a foreign element instead of the owning document — so the caller is returned
# control with event-handler attributes still attached to surviving
# descendants. The agent must first write its own reproduction as
# /app/repro.js (fails against the buggy build, passes against the repaired
# build), then fix the source so the symptom disappears.
#
# The verifier:
#   0. asserts tree provenance (HEAD still the pinned parent commit; the
#      upstream fix commit is not reachable; src/purify.ts holds a non-empty
#      diff; test/test-suite.js is byte-identical to the parent commit; and no
#      path outside src/ or dist/ changed);
#   1. requires the agent's own reproduction to FAIL against the pristine
#      pre-fix tree (the parent commit's committed dist blob) and to PASS
#      against a dist regenerated by the verifier from the agent's source —
#      the agent's dist is rebuilt from the working tree with the project's
#      own build, so patching the prebuilt binary without fixing the source
#      cannot survive;
#   2. overlays the project's own regression tests from the FIX commit (the
#      two IN_PLACE ownerDocument-clobber QUnit cases, extracted at image
#      build time into /opt/golden) onto the repaired tree and runs the
#      project's own full jsdom suite — it must be fully green (1205 tests at
#      this pin), naming the two golden cases explicitly;
#   3. compiles nothing but runs three authored hidden-case drivers against the
#      rebuilt dist: a deep subtree with a shadowed form root and an
#      <input name="ownerDocument"> child, a non-form root with a javascript:
#      href payload, and a "vicious" accessor whose getter throws. Every case
#      must complete without a throw, strip the armed handler, and preserve the
#      page's poisoned property / benign attributes.
#
# Reward is binary and written on every exit path (trap below).

trap '[ -f /logs/verifier/reward.txt ] || { echo "VERIFIER EXITED WITHOUT WRITING A REWARD; scoring 0" >&2; mkdir -p /logs/verifier; echo 0 > /logs/verifier/reward.txt; }' EXIT
set -u
mkdir -p /logs/verifier
reward=1

SRC=/app/src
REPRO=/app/repro.js
PARENT_SHA=2c8ca25ef3cec05e12a50bd456f57a816eaa5998
FIX_SHA=0332fe7cd45ad7971935e78c210c4714be4662ad
GOLDEN=/opt/golden/test-suite.js
GOLDEN_SHA=52b94a4e66224f758a8b5785d57060c00009b282e4c0f66ad6d8b447851a831c
NODE_ENV=node
export NODE_PATH=${SRC}/node_modules

fail() {  # fail MESSAGE
  echo "FAIL: $1" >&2
  reward=0
}

# ---------- 0. tree provenance -----------------------------------------------
echo "== tree provenance =="
if [ ! -d "$SRC/.git" ]; then
  fail "/app/src is not a git clone"
elif [ "$(git -C "$SRC" rev-parse HEAD 2>/dev/null)" != "$PARENT_SHA" ]; then
  fail "/app/src HEAD is not the pinned parent commit"
else
  echo "ok: HEAD is $PARENT_SHA"
fi

if [ ! -f "$REPRO" ] || [ ! -s "$REPRO" ]; then
  fail "deliverable /app/repro.js is missing or empty"
else
  echo "ok: /app/repro.js exists"
fi

if git -C "$SRC" cat-file -e "${FIX_SHA}^{commit}" 2>/dev/null; then
  fail "the upstream fix commit is reachable from the working clone"
else
  echo "ok: the upstream fix commit is not present in the clone"
fi

if git -C "$SRC" diff --quiet HEAD -- src/purify.ts 2>/dev/null; then
  fail "the deliverable /app/src has no source change (src/purify.ts was not fixed)"
else
  echo "ok: src/purify.ts differs from the pinned commit"
fi

if git -C "$SRC" diff --quiet HEAD -- test/test-suite.js 2>/dev/null; then
  echo "ok: test/test-suite.js is untouched (byte-identical to the parent commit)"
else
  fail "test/test-suite.js was modified (the project's own tests must stay pristine)"
fi

changed=$(git -C "$SRC" diff --name-only HEAD 2>/dev/null || true)
for p in $changed; do
  case "$p" in
    src/*|dist/*) : ;;
    *) fail "unexpected working-tree change outside src/ and dist/: $p" ;;
  esac
done
echo "ok: working tree changes are confined to src/ and dist/"

if ! grep -qE "sanitize|DOMPURIFY" "$REPRO" 2>/dev/null; then
  fail "/app/repro.js does not exercise the DOMPurify library"
else
  echo "ok: /app/repro.js references the sanitizer"
fi

# ---------- 1. the agent's own reproduction, both directions -----------------
echo "== reproduction: must fail on the pre-fix tree =="
mkdir -p /tmp/pre-fix
if ! git -C "$SRC" show "${PARENT_SHA}:dist/purify.cjs.js" > /tmp/pre-fix/purify.cjs.js 2>/dev/null; then
  fail "could not extract the pristine parent dist blob"
fi
if DOMPURIFY_MODULE=/tmp/pre-fix/purify.cjs.js node "$REPRO" > /tmp/repro-prefix.log 2>&1; then
  fail "the reproduction exited 0 against the pre-fix tree (it does not expose the bug)"
  tail -5 /tmp/repro-prefix.log | sed 's/^/    /' >&2
else
  echo "ok: reproduction fails against the pre-fix tree (nonzero exit)"
fi

# ---------- 2. rebuild dist from the agent's source --------------------------
echo "== rebuilding dist from the repaired source =="
if ( cd "$SRC" && npm run build --no-progress > /tmp/rebuild.log 2>&1 ); then
  echo "ok: npm run build succeeded"
else
  fail "npm run build failed on the repaired tree"
  tail -20 /tmp/rebuild.log | sed 's/^/    /' >&2
fi

echo "== reproduction: must pass on the repaired tree =="
if DOMPURIFY_MODULE="$SRC/dist/purify.cjs.js" node "$REPRO" > /tmp/repro-fixed.log 2>&1; then
  echo "ok: reproduction passes against the repaired build"
else
  fail "the reproduction still fails against the repaired build"
  tail -5 /tmp/repro-fixed.log | sed 's/^/    /' >&2
fi

# ---------- 3. golden regression tests + the project's own full suite --------
echo "== overlay the project's own regression tests and run the full jsdom suite =="
if [ "$(sha256sum "$GOLDEN" 2>/dev/null | cut -d' ' -f1)" != "$GOLDEN_SHA" ]; then
  fail "golden regression file /opt/golden/test-suite.js is missing or wrong"
fi
if [ "$reward" = 1 ]; then
  cp "$SRC/test/test-suite.js" /tmp/orig-test-suite.js
  cp "$GOLDEN" "$SRC/test/test-suite.js"
  ( cd "$SRC" && node test/jsdom-node-runner > /tmp/suite.log 2>&1 )
  rc=$?
  cp /tmp/orig-test-suite.js "$SRC/test/test-suite.js"
  if [ "$rc" -eq 0 ]; then
    echo "ok: full jsdom suite green with the regression tests overlaid"
  else
    fail "the project's own suite is not fully green"
    grep -E "not ok" /tmp/suite.log | head -6 | sed 's/^/    /' >&2
    tail -4 /tmp/suite.log | sed 's/^/    /' >&2
  fi
  for name in "a clobbered ownerDocument does not skip the fail-closed scrub" \
              "form with a natural ownerDocument-clobbering child stays safe"; do
    if grep -qE "^# test: IN_PLACE: ${name}$" /tmp/suite.log; then
      echo "ok: golden case ran in the suite: IN_PLACE: $name"
    else
      fail "golden case was not part of the run: $name"
    fi
  done
fi

# ---------- 4. authored hidden cases -----------------------------------------
echo "== hidden cases =="
n_hidden=0
for case in /tests/hidden/*/; do
  [ -d "$case" ] || continue
  n_hidden=$((n_hidden + 1))
  cname=$(basename "$case")
  f="$case/run.js"
  if [ ! -f "$f" ]; then
    fail "hidden case $cname has no run.js"
    continue
  fi
  out=$(DOMPURIFY_MODULE="$SRC/dist/purify.cjs.js" node "$f" 2>&1)
  rc=$?
  if [ "$rc" -eq 0 ] && ! printf '%s\n' "$out" | grep -q "HIDDEN-FAIL"; then
    echo "ok: hidden case $cname"
  else
    fail "hidden case $cname (rc=$rc)"
    printf '%s\n' "$out" | grep -E "HIDDEN-FAIL|THREW" | head -6 | sed 's/^/    /' >&2
  fi
done
if [ "$n_hidden" -lt 3 ]; then
  fail "fewer than three hidden cases were exercised"
fi

echo "REWARD=$reward"
echo "$reward" > /logs/verifier/reward.txt
exit 0