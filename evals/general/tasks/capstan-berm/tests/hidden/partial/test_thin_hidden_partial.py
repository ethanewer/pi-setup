def test_thin_partial_iter1_preserves_input():
    img = _disc()
    original = img.copy()
    skeleton = thin(img, max_num_iter=1)
    np.testing.assert_array_equal(img, original)
    np.testing.assert_array_equal(skeleton, DISC_ITER1)


