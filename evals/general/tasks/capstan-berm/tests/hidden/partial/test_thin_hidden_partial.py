def test_thin_partial_budget_calls_do_not_accumulate():
    """Calling thin on the SAME array with increasing budgets must not corrupt
    it: every call sees the pristine original, so each result is exactly the
    partial skeleton for that budget (partial results are nested)."""
    img = _disc()
    original = img.copy()
    s1 = thin(img, max_num_iter=1)
    np.testing.assert_array_equal(img, original)
    s2 = thin(img, max_num_iter=2)
    np.testing.assert_array_equal(img, original)
    s4 = thin(img, max_num_iter=4)
    np.testing.assert_array_equal(img, original)
    sall = thin(img)
    np.testing.assert_array_equal(img, original)
    # thinning only ever removes pixels: more budget means a subset
    assert np.all(s2 <= s1)
    assert np.all(s4 <= s2)
    assert np.all(sall <= s4)