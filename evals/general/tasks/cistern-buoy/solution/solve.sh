#!/bin/bash
# cistern-buoy oracle: fix the HSTS-cache-destruction bug in the real curl
# tree, rebuild the binary, and write the root-cause write-up.
#
# The fix is the same one upstream adopted for this bug: cap the max-age
# parsed from Strict-Transport-Security at two years (so an unrepresentable
# expiry can never enter the in-memory cache) and make cache saving skip an
# entry it cannot format instead of aborting the whole save (so the file
# already truncated by the save is never left empty). The fix logic lives in
# /solution/fix_hsts.py; the shims here run it, rebuild, document and smoke
# the result without reading any expectation files.
set -eu

SRC=/app/src

# ---- 1. Apply the fix to the source tree (real work, no hardcoding). ----
python3 /solution/fix_hsts.py

# ---- 2. Rebuild incrementally so /app/src/src/curl reflects the fix. ----
( cd "$SRC" && make -j1 )

# ---- 3. Root-cause write-up. ----
cat > /app/diagnosis.md <<'MD'
# Diagnosis: an extreme Strict-Transport-Security max-age destroys the HSTS cache

## Symptom

A server response carrying `Strict-Transport-Security: max-age=<huge>` (for
example `max-age=1152921504606846976`, 2^60) makes curl destroy the on-disk
HSTS cache it maintains with `--hsts <file>`: after the request finishes and
the cache is written back, the file is 0 bytes. Every previously remembered
secure-only host is forgotten and the current server is not recorded either.
One such response disables the user's HSTS memory until the cache is rebuilt
from scratch.

## Root cause

When an HSTS response header is processed, the parsed `max-age` (a relative
number of seconds) is capped only at the platform's maximum timestamp
(`TIME_T_MAX`), so a huge but non-overflowing value like 2^60 is accepted and
stored as the entry's absolute expiry (`now + 2^60`). When the cache is later
saved, each entry's expiry is formatted to a `YYYYMMDD HH:MM:SS` calendar
date with `curlx_gmtime()`. That conversion fails for a timestamp decades
beyond the representable range. One entry failing to format returned an error
from the entry writer, which aborted the whole save loop with the target
file already truncated to zero bytes (the save opens and truncates the
destination up front, writing to a temporate file that is only renamed over
it on success). Net effect: the cache file ends up empty.

## Fix

- Cap `max-age` when parsing the header: a value beyond
  `2*365*24*3600` seconds (two years, matching what browsers apply) is
  clamped to that cap, so no unrepresentable expiry can ever enter the
  in-memory cache in the first place.
- Make saving resilient: if a single entry's expiry still cannot be turned
  into a calendar date, that entry is skipped instead of aborting the
  save, so the remaining entries (including entries loaded from the file
  before the request and the just-seen server) are still persisted under the
  properly written temporary file, which is then renamed over the original.

With the fixed clock of the reproducer (`CURL_TIME=1920582000`) the capped
entry for the current server is `this.hsts.example "20321109 23:00:00"` and
the previously cached hosts survive exactly as they were.
MD

# ---- 4. Smoke: the instruction's reproducer must now leave a full cache. ----
python3 - <<'PY' &
from http.server import BaseHTTPRequestHandler, HTTPServer
class H(BaseHTTPRequestHandler):
    def do_GET(self):
        body = b'-foo-'
        self.send_response(200)
        self.send_header('Date', 'Tue, 09 Nov 2010 14:49:00 GMT')
        self.send_header('Content-Length', str(len(body)))
        self.send_header('Connection', 'close')
        self.send_header('Strict-Transport-Security', 'max-age=1152921504606846976')
        self.end_headers()
        self.wfile.write(body)
    def log_message(self, *args):
        pass
HTTPServer(('127.0.0.1', 8891), H).serve_forever()
PY
srv=$!
trap 'kill $srv 2>/dev/null || true' EXIT
for _ in $(seq 1 50); do
    if ( exec 3<>/dev/tcp/127.0.0.1/8891 ) 2>/dev/null; then break; fi
    sleep 0.2
done

cd /tmp
cat > hsts_in <<'EOF'
# Your HSTS cache. https://curl.se/docs/hsts.html
# This file was generated by libcurl! Edit at your own risk.
somehere.example "20330525 03:33:20"
elsewhere.example.com "20330727 03:33:20"
EOF
CURL_HSTS_HTTP=yes CURL_TIME=1920582000 \
  /app/src/src/curl -s -o /dev/null --hsts ./hsts_in \
  --resolve this.hsts.example:8891:127.0.0.1 http://this.hsts.example:8891/

python3 - <<'PY'
import pathlib
data = pathlib.Path('/tmp/hsts_in').read_bytes()
expected = (
    b'# Your HSTS cache. https://curl.se/docs/hsts.html\n'
    b'# This file was generated by libcurl! Edit at your own risk.\n'
    b'somehere.example "20330525 03:33:20"\n'
    b'elsewhere.example.com "20330727 03:33:20"\n'
    b'this.hsts.example "20321109 23:00:00"\n')
assert data == expected, f'smoke: cache content mismatch ({len(data)} bytes)'
print(f'smoke ok: cache is {len(data)} bytes, capped entry recorded, seeds intact')
PY

# ---- 5. The project's own HSTS-related tests must stay green. ----
( cd "$SRC" && cd tests && ./runtests.pl -n 1 1660 >/tmp/oracle_tests.log 2>&1 )

echo "oracle done: fixed tree, rebuilt /app/src/src/curl, wrote /app/diagnosis.md"