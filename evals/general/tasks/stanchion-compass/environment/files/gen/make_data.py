#!/usr/bin/env python3
"""Deterministic generator for stanchion-compass heavy route data modules.

Each route view ships with a big, plausible data module so the naive build
has one enormous entry bundle. Generation is a pure function of the module id
(integer LCG + crc32, no imports, no clock, no environment) so any two builds
of the image produce byte-identical sources.

Output goes to src/lib/ relative to the current working directory.
"""
import os
import zlib

OUT = os.path.join("src", "lib")
os.makedirs(OUT, exist_ok=True)


def lcg(seed):
    state = seed & 0xFFFFFFFF

    def rand():
        nonlocal state
        state = (state * 1103515245 + 12345) & 0xFFFFFFFF
        return state

    return rand


def cr(seed, s):
    return zlib.crc32(("%d:%s" % (seed, s)).encode("utf-8"))


WORDS = (
    "aperture baffle cascade damper eddy flux gauge hearth intake jet kiln "
    "lumen manifold nozzle orifice plenum quench rotor stator throttle uptake "
    "valve windlass yoke zone amperage band coil drift emissivity fault "
    "gradient hysteresis interval joule kernel lamina margin notch offset "
    "pitch quadrant ripple sag tolerance undulation variance warp xanthate "
    "yield zeta baseline clamp delta echo focal gain haze index lathe moire "
    "nodal order pulse quote ramp sample tack uv vacuum wash xylene yaw "
).split()


def sentence(sexp):
    n = 6 + (sexp % 7)
    acc = []
    for i in range(n):
        acc.append(WORDS[(sexp + i * 31) % len(WORDS)])
    return " ".join(acc) + "."


def body_text(seed, bidx):
    sentences = []
    n = 7 + (cr(seed, "body-%d" % bidx) % 6)
    for j in range(n):
        sentences.append(sentence(cr(seed, "sent-%d-%d" % (bidx, j))))
    return " ".join(sentences)


def fmt(f):
    """Deterministic float formatting, ~35.12345."""
    s = int(round(f * 100000.0))
    sign = "-" if s < 0 else ""
    s = abs(s)
    return "%s%d.%05d" % (sign, s // 100000, s % 100000)


# ---------------------------------------------------------------------------
# chartsData.ts  (~330 KB minified)
# ---------------------------------------------------------------------------
def gen_charts():
    seed = 0x9F31
    rnd = lcg(seed + 7)
    lines = [
        "// generated by gen/make_data.py (deterministic; do not edit by hand)",
        "// Telemetry fixture: station network time series.",
        "",
        "export interface SeriesPoint { t: number; v: number }",
        "export interface Station { name: string; color: string; series: SeriesPoint[] }",
        "",
        'export const CHART_HEAD = "scm_9f31_charts";',
        'export const CHART_MARKER = "sc_mk_9f31_charts";',
        "",
        "const PALETTE = [",
    ]
    pal = []
    for i in range(96):
        c = ("#%02x%02x%02x" % (rnd() % 0xE0 + 0x10, rnd() % 0xE0 + 0x10, rnd() % 0xE0 + 0x10))
        pal.append(c)
    lines.append(",\n".join('  "%s"' % c for c in pal))
    lines.extend([",", "];", ""])

    lines.append("export const STATIONS: Station[] = [")
    stations = []
    names = []
    for st in range(34):
        name = "station-" + ("abcdefghijklmnopqrstuvwxyz" + "0123456789")[st % 36] + ("%02d" % st)
        names.append(name)
        col = pal[(st * 7) % len(pal)]
        npts = 401
        pts = []
        base = (rnd() % 4000) / 10.0 - 200.0
        acc = base
        for k in range(npts):
            t = k * 2
            acc += ((rnd() % 2000) / 100.0 - 10.0)
            v = acc + (rnd() % 200) / 100.0
            pts.append("{t:%d,v:%s}" % (t, fmt(v)))
        stations.append(
            '  { name: "%s", color: "%s", series:\n    [%s] }'
            % (name, col, ",".join(pts))
        )
    lines.append(",\n".join(stations))
    lines.extend([",", "];", ""])

    lines.append("export const LAST_VALUES: Record<string, string> = {")
    lv = []
    for st, name in enumerate(names):
        lastv = 0.0
        init = (rnd() % 4000) / 10.0 - 200.0
        acc = init
        for k in range(401):
            acc += ((rnd() % 2000) / 100.0 - 10.0)
            lastv = acc + (rnd() % 200) / 100.0
        lv.append('  "%s": "%s"' % (name, fmt(lastv)))
    lines.append(",\n".join(lv))
    lines.extend([",", "};", ""])

    res = []
    for i in range(64):
        res.append('  "%s"' % fmt((rnd() % 40000) / 10.0))
    lines.append("const RESEED_TABLE = [")
    lines.append(",\n".join(res))
    lines.extend([",", "];", ""])
    lines.extend(
        [
            "",
            "export function reseedChart(seed: number): string {",
            "  const idx = ((seed - 1) % RESEED_TABLE.length + RESEED_TABLE.length) % RESEED_TABLE.length;",
            '  return "9f31:" + RESEED_TABLE[idx];',
            "}",
            "",
        ]
    )
    with open(os.path.join(OUT, "chartsData.ts"), "w") as fh:
        fh.write("\n".join(lines))
    return os.path.getsize(os.path.join(OUT, "chartsData.ts"))


# ---------------------------------------------------------------------------
# reportTemplates.ts  (~280 KB minified)
# ---------------------------------------------------------------------------
def gen_reports():
    seed = 0xD20A
    lines = [
        "// generated by gen/make_data.py (deterministic; do not edit by hand)",
        "// Report catalogue fixture.",
        "",
        "export interface ReportTemplate { id: string; cat: number; level: string; title: string; body: string }",
        "",
        'export const REPORT_HEAD = "scm_d20a_reports";',
        'export const REPORT_MARKER = "sc_mk_d20a_reports";',
        "",
        "export const TEMPLATES: ReportTemplate[] = [",
    ]
    recs = []
    for i in range(1200):
        title = body_text(seed, i).split(".")[0][:42]
        body = body_text(seed, 9000 + i)
        recs.append(
            '{ id: "TMPL-%04d", cat: %d, level: "l%d", title: "%s", body: "%s" }'
            % (
                i,
                i % 5,
                i % 4 + 1,
                title.replace('"', "'"),
                body.replace('"', "'"),
            )
        )
    lines.append(",\n".join(recs))
    lines.extend([",", "];", ""])

    lines.extend(
        [
            "const BODY_BY_ID: Record<string, string> = {};",
            "for (const t of TEMPLATES) BODY_BY_ID[t.id] = t.body;",
            "",
            "export function expandTemplate(id: string): string {",
            "  return BODY_BY_ID[id] ?? '';",
            "}",
            "",
        ]
    )
    with open(os.path.join(OUT, "reportTemplates.ts"), "w") as fh:
        fh.write("\n".join(lines))
    return os.path.getsize(os.path.join(OUT, "reportTemplates.ts"))


# ---------------------------------------------------------------------------
# auditIndex.ts  (~230 KB minified)
# ---------------------------------------------------------------------------
def gen_admin():
    seed = 0x73B4
    lines = [
        "// generated by gen/make_data.py (deterministic; do not edit by hand)",
        "// Audit index fixture.",
        "",
        "export interface AuditEntry { id: string; desc: string }",
        "",
        'export const AUDIT_HEAD = "scm_73b4_admin";',
        'export const AUDIT_MARKER = "sc_mk_73b4_admin";',
        "",
        "export const AUDIT_INDEX: AuditEntry[] = [",
    ]
    recs = []
    for i in range(3600):
        desc = body_text(seed, 20000 + i).split(".")[0].replace('"', "'")
        recs.append('  { id: "0x%08x", desc: "%s" }' % (cr(seed, "id-%d" % i), desc))
    lines.append(",\n".join(recs))
    lines.extend([",", "];", ""])

    # Checksum over the index, precomputed at generation time (plain FNV-1a).
    h = 0x811C9DC5
    for i in range(3600):
        h ^= cr(seed, "id-%d" % i) & 0xFF
        h = (h * 0x01000193) & 0xFFFFFFFF
        h ^= (cr(seed, "id-%d" % i) >> 8) & 0xFF
        h = (h * 0x01000193) & 0xFFFFFFFF
    lines.extend(
        [
            "",
            'const CHECKSUM = "%08x";' % h,
            "",
            "export function auditChecksum(): string {",
            '  return "73b4:" + CHECKSUM;',
            "}",
            "",
        ]
    )
    with open(os.path.join(OUT, "auditIndex.ts"), "w") as fh:
        fh.write("\n".join(lines))
    return os.path.getsize(os.path.join(OUT, "auditIndex.ts"))


def main():
    sizes = {
        "chartsData.ts": gen_charts(),
        "reportTemplates.ts": gen_reports(),
        "auditIndex.ts": gen_admin(),
    }
    total = 0
    for name, sz in sizes.items():
        print("generated src/lib/%s (%d bytes)" % (name, sz))
        total += sz
    print("total heavy data: %d bytes" % total)
    assert total > 600000, "generated data too small: %d" % total


if __name__ == "__main__":
    main()