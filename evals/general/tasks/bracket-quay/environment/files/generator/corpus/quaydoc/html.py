"""Page-level HTML rendering: the document shell around rendered content.

The content itself is produced by :mod:`quaydoc.blocks`; this module layers
on the ``<head>``, navigation sidebar, table-of-contents panel and footer,
keeping every internal URL root-relative so the site works under the dev
server, a static host, or a file:// mount alike.
"""

from __future__ import annotations

from quaydoc import blocks, theme, toc as _toc
from quaydoc.util import escape_attr, escape_html


def render_page_html(page, site):
    """Render ``page`` (which must already have ``.html_content`` set) into a
    complete HTML document string."""
    ctx = blocks.RenderContext(page, site, site.resolver)
    content = page.html_content
    title = page.title or site.config.title
    head_title = f"{page.title} · {site.config.title}" if page.title else \
        site.config.title
    description = page.description or ""
    sidebar = site.nav_html(page.url)
    if page.show_toc and page.sections:
        toc_panel = _toc.toc_html(page.sections, page.current_anchor)
    else:
        toc_panel = ""

    parts = [
        "<!DOCTYPE html>\n",
        '<html lang="en">\n<head>\n',
        '<meta charset="utf-8">\n',
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n',
        f"<title>{escape_html(head_title)}</title>\n",
    ]
    if description:
        parts.append(f'<meta name="description" content='
                     f'"{escape_attr(description)}">\n')
    parts.append('<link rel="stylesheet" href="/assets/style.css">\n')
    if site.config.rss:
        parts.append('<link rel="alternate" type="application/atom+xml" '
                     'title="Atom feed" href="/feed.xml">\n')
    if site.config.search:
        parts.append('<link rel="alternate" type="application/json" '
                     'title="Search index" href="/search_index.json">\n')
    parts.append('</head>\n<body>\n')
    parts.append('<header class="site-header">'
                 '<span class="brand">quaydoc</span>'
                 '<button class="nav-toggle" type="button">Menu</button>'
                 "</header>\n")
    parts.append(f'<nav class="sidebar">{sidebar}</nav>\n')
    parts.append('<main class="content">\n')
    if page.title:
        parts.append(f'<h1>{escape_html(page.title)}</h1>\n')
    parts.append(content)
    parts.append("</main>\n")
    if toc_panel not in ("", "<ul class=\"toc\"></ul>"):
        parts.append(f'<aside class="toc-panel"><h2>On this page</h2>'
                     f"{toc_panel}</aside>\n")
    parts.append('<footer class="site-footer">Generated by '
                 f"quaydoc {escape_html(site.version)}")
    github = getattr(site.config, "github_repo", None)
    if github:
        parts.append(f' · <a href="{escape_attr(github)}" rel="noopener" '
                     'target="_blank">Edit on GitHub</a>')
    parts.append("</footer>\n")
    parts.append('<script src="/assets/quaydoc.js"></script>\n')
    parts.append("</body>\n</html>\n")
    return "".join(parts)



import re

_EXT_LINK_RE = re.compile(
    r'(<a\s[^>]*href=")(https?://[^"#]+)("[^>]*)(>)')
_JS_LINK_RE = re.compile(r'href="javascript:[^"]*"|'
                         r'href="data:text/html[^"]*"')
_REL_RE = re.compile(r'rel="[^"]*"')


def postprocess(html, new_tab=False):
    """Apply the configured rewrites to rendered HTML output."""
    html = _neutralise_bad_links(html)
    html = _annotate_external_links(html, new_tab)
    return html


def _neutralise_bad_links(html):
    return _JS_LINK_RE.sub('href="#"', html)


def _annotate_external_links(html, new_tab):
    rel = "noopener noreferrer" if new_tab else "noopener"

    def _rewrite(match):
        prefix, url, between, end = match.groups()
        if "rel=" in between:
            between = _REL_RE.sub(f'rel="{rel}"', between)
        else:
            between = between.rstrip() + f' rel="{rel}"'
        if new_tab and "target=" not in between:
            between = between.rstrip() + ' target="_blank"'
        return prefix + url + between + end

    return _EXT_LINK_RE.sub(_rewrite, html)


def ensure_trailing_newline(html):
    return html if html.endswith("\n") else html + "\n"