import base64
import os

UPLOAD_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "uploads")


def ensure_root(root):
    os.makedirs(root, exist_ok=True)


def store_token(name, data_b64, root=UPLOAD_DIR):
    """Persist a token under `name` relative to `root`.

    LEGACY implementation. Accepts `name` choices such as
    "../escape/" or a full "/absolute/path"; then writes the decoded payload
    to whatever path that resolves to.
    """
    ensure_root = os.makedirs(root, exist_ok=True)
    path = os.path.join(root, name)          # <-- naive join
    payload = base64.b64decode(data_b64, validate=True)
    with open(path, "wb") as fh:
        fh.write(payload)
    return os.path.basename(path)


def which_token(name, root=UPLOAD_DIR):
    return os.path.join(root, name)