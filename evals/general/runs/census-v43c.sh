#!/usr/bin/env bash
# Acceptance census for the v4.3c wave.
#
# Re-runs the both-direction gate over every landed task, sharded, and records
# the OBSERVED rewards parsed out of each task's raw harbor reward.txt rather
# than the gate's own PASS/FAIL line. A summary line is what a verifier writes
# about itself; the reward file is what it actually returned.
#
# This exists because the suite's own history keeps finding tasks that passed
# their author and their independent reviewer and still failed a census. Three
# earlier waves each caught at least one.
#
# Safe to run while the authoring wave is still reviewing, as long as the tasks
# under review are excluded: verify_new_task.sh uses a PID-suffixed gate cache
# and a per-task job directory, so concurrent invocations do not collide.
#
#   SHARDS=8 EXCLUDE=a,b,c bash runs/census-v43c.sh
#
# Resumes by default: a task already recorded rc=0 is skipped, so raising
# SHARDS costs nothing already measured. Set RESUME=0 to start clean.
#
# DO NOT EDIT THIS FILE WHILE IT IS RUNNING. Bash reads a script incrementally
# rather than loading it whole, so an edit shifts the byte offsets the running
# shell is reading from and it resumes execution mid-instruction. Doing exactly
# that during the 8-shard run made the interpreter fall off the end of the tally
# block and exit 2, after all the work had completed and been written. The results
# were fine and re-running the tally by hand gave the right answer, but the run's
# own final summary was lost. Copy the script and edit the copy, or wait.
set -uo pipefail
cd /home/ee/pi-setup/evals/general || exit 2

OUT=${OUT:-/tmp/v43c-census}
# Shards are cheap here. The first run used 2 on the assumption that docker
# contention was the limit, but vmstat showed the host 88% idle at 1% iowait
# while a single harbor trial ran 25 minutes: the work is long and mostly
# waiting, not CPU- or I/O-bound. Throughput is therefore set by shard count,
# and 2 shards capped the wave near 5 tasks/hour on a 64-core box.
SHARDS=${SHARDS:-8}
RESUME=${RESUME:-1}
# Tasks whose reviewer is still running would be censused mid-edit, and
# futtock-careen was never authored. Both are excluded by default.
EXCLUDE=${EXCLUDE:-companion-berm,companion-flint,crance-bell,crojack-wheel,futtock-careen}
# ONLY=name,name restricts the run to those tasks and ignores EXCLUDE. Used for
# the final pass over tasks that were under review while the main census ran:
# their result has to be re-measured after the reviewer stops editing, and the
# resume filter would otherwise skip them on the strength of a stale pass.
ONLY=${ONLY:-}

if [ "$RESUME" = 1 ] && [ -f "$OUT/rc.txt" ]; then
  echo "resuming from $OUT ($(grep -c ' rc=0$' "$OUT/rc.txt" 2>/dev/null || echo 0) tasks already passed)"
else
  rm -rf "$OUT"
fi
mkdir -p "$OUT"
echo "$EXCLUDE" | tr ',' '\n' | sed '/^$/d' | sort -u > "$OUT/exclude.txt"

python3 - "$OUT" "$ONLY" <<'PY' > "$OUT/tasks.txt"
import json, os, sys
out, only = sys.argv[1], sys.argv[2]
excl = set(open(f'{out}/exclude.txt').read().split())
slots = [x['name'] for x in json.load(open('specs/v43c_slots.json'))]
want = {n.strip() for n in only.split(',') if n.strip()}
for n in slots:
    if want:
        if n not in want:
            continue
    elif n in excl:
        continue
    if os.path.exists(f'tasks/{n}/task.toml'):
        print(n)
PY

# Drop tasks already recorded as passing, so a resume or a shard increase only
# measures what is still outstanding. A task interrupted mid-trial has a partial
# log but no rc line, so it is correctly re-run.
if [ -f "$OUT/rc.txt" ]; then
  grep ' rc=0$' "$OUT/rc.txt" 2>/dev/null | awk '{print $1}' | sort -u > "$OUT/passed.txt" || : > "$OUT/passed.txt"
  if [ -s "$OUT/passed.txt" ]; then
    grep -vxF -f "$OUT/passed.txt" "$OUT/tasks.txt" > "$OUT/todo.txt" || : > "$OUT/todo.txt"
    mv "$OUT/todo.txt" "$OUT/tasks.txt"
  fi
fi

n=$(wc -l < "$OUT/tasks.txt")
if [ -n "$ONLY" ]; then
  echo "=== [$(date -Is)] targeted census: $n task(s), $SHARDS shards ==="
  echo "    only: $ONLY"
else
  echo "=== [$(date -Is)] census over $n outstanding tasks, $SHARDS shards ==="
  echo "    excluded: $(tr '\n' ' ' < "$OUT/exclude.txt")"
fi
echo "    disk before: $(df -h / | awk 'NR==2{print $3" used, "$4" free"}')"
[ "$n" -gt 0 ] || { echo "nothing to do"; exit 0; }

: > "$OUT/rc.txt"
split -n r/$SHARDS -d "$OUT/tasks.txt" "$OUT/shard"
for s in "$OUT"/shard*; do
  ( while read -r t; do
      [ -n "$t" ] || continue
      bash tools/verify_new_task.sh "$t" >"$OUT/$t.log" 2>&1
      r=$?
      # Capture rc once. Reading $? a second time would report the status of the
      # echo that wrote rc.txt, which is always 0 and would hide every failure.
      echo "$t rc=$r" >> "$OUT/rc.txt"
      echo "=== [$(date -Is)] done $t rc=$r ($(wc -l < "$OUT/rc.txt")/$n)"
    done < "$s" ) &
done
wait

echo
echo "=== [$(date -Is)] census complete ==="
echo "    disk after: $(df -h / | awk 'NR==2{print $3" used, "$4" free"}')"

# Tally from the raw reward values the gate recorded, not from its rc.
python3 - "$OUT" <<'PY'
import re, sys, pathlib
out = pathlib.Path(sys.argv[1])


def read_set(p, parse_rc=False):
    if not p.exists():
        return {}
    d = {}
    for line in p.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        if parse_rc:
            parts = line.rsplit(' rc=', 1)
            if len(parts) == 2:
                d[parts[0]] = parts[1]
        else:
            d[line] = '0'
    return d


rc = read_set(out / 'rc.txt', parse_rc=True)
# Tasks that passed in an earlier run. They count as rc=0 here, and treating a
# missing rc lookup as a failure instead would have reported every resumed task
# as broken.
prior = read_set(out / 'passed.txt')
rc = {**prior, **rc}

ok, bad, nolog = [], [], []


def as_num(s):
    """Compare rewards numerically.

    harbor writes `1` and `0` into verifier/reward.txt, and verify_new_task.sh
    compares against want=1 and want=0 as strings. The first version of this tally
    compared against '1.0' and '0.0' and so reported all 102 passing tasks as
    failures. It had been tested against synthetic logs whose reward values were
    written as '1.0' and '0.0' to match the parser, so the test confirmed the
    assumption instead of the data. Fixtures for a parser have to come from real
    output.
    """
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


for t in sorted(rc):
    log = out / f'{t}.log'
    if not log.exists():
        nolog.append(t); continue
    txt = log.read_text(errors='replace')
    # Parse the reward the gate read out of harbor's verifier/reward.txt. Taking
    # the gate's own PASS line instead would be trusting a summary about itself.
    pat = re.compile(r"^\s+(oracle|nop): harbor_rc=(-?\d+) reward='([^']*)'", re.M)
    got = {m.group(1): (m.group(2), m.group(3)) for m in pat.finditer(txt)}
    o, nn = got.get('oracle'), got.get('nop')
    problems = []
    if o is None: problems.append('no oracle reward line')
    elif as_num(o[1]) != 1.0: problems.append(f'oracle reward={o[1]!r} (want 1)')
    if nn is None: problems.append('no nop reward line')
    elif as_num(nn[1]) != 0.0: problems.append(f'nop reward={nn[1]!r} (want 0)')
    if rc[t] != '0': problems.append(f'gate rc={rc[t]}')
    (bad.append((t, problems)) if problems else ok.append(t))

print(f'censused {len(rc)} tasks: PASS {len(ok)}  FAIL {len(bad)}  no-log {len(nolog)}')
for t, p in bad:
    print(f'  FAIL {t}: ' + '; '.join(p))
for t in nolog:
    print(f'  NO LOG {t}')
if not bad and not nolog:
    print('  every task earned oracle reward 1 and nop reward 0')
PY
