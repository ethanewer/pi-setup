#!/usr/bin/env python3
"""Reproducibility gate (TODO.md section 6).

Two modes:

  default                content-freeze check: every task-owned file must match
                         the SHA-256 recorded in specs/provenance.json, and
                         every file must have a provenance entry.  Detects any
                         drift after the suite was frozen; the audits must be
                         re-run after any change.

  --compare-jobs A B     compare two full harbor oracle runs (job output dirs).
                         Same task set and identical rewards are required;
                         this is the "run it again" reproducibility check.

Fails closed when inputs are missing.
"""
import argparse, hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OWNED = ('tasks', 'specs', 'tools', 'agents')


def sha_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open('rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def content_freeze() -> int:
    prov_path = ROOT / 'specs/provenance.json'
    if not prov_path.exists():
        print('ERROR specs/provenance.json missing (run tools/update_provenance.py)')
        return 1
    prov = json.loads(prov_path.read_text()).get('task_files', {})
    problems = []
    seen = set()
    for sub in OWNED:
        base = ROOT / sub
        if not base.exists():
            continue
        for p in sorted(base.rglob('*')):
            if not p.is_file() or '__pycache__' in p.parts:
                continue
            rel = str(p.relative_to(ROOT))
            seen.add(rel)
            if sub == 'specs' and p.name in ('provenance.json',
                                             'independence_report.json',
                                             'similarity_report.json',
                                             'oracle_report.json',
                                             'oracle_times.json'):
                continue  # reports regenerated by the audits themselves
            entry = prov.get(rel)
            if entry is None:
                problems.append(f'no provenance entry: {rel}')
                continue
            if entry.get('sha256') != sha_file(p):
                problems.append(f'hash drift since freeze: {rel}')
    for rel in prov:
        if rel not in seen and rel.startswith(OWNED):
            problems.append(f'provenance entry for deleted file: {rel}')
    print(f'checked={len(seen)} drift_problems={len(problems)}')
    for p in problems[:60]:
        print('ERROR', p)
    return 1 if problems else 0


def load_job(job_dir: Path) -> dict:
    """task -> reward for every trial under a harbor job directory."""
    rewards = {}
    for trial in sorted(job_dir.rglob('result.json')):
        try:
            data = json.loads(trial.read_text())
        except Exception:
            continue
        task = data.get('task_name')
        if not task:
            continue
        rp = trial.parent / 'verifier/reward.txt'
        reward = None
        if rp.exists():
            try:
                reward = float(rp.read_text().strip())
            except ValueError:
                reward = None
        rewards[task] = reward
    return rewards


def compare_jobs(a: Path, b: Path) -> int:
    if not a.exists() or not b.exists():
        print(f'ERROR job dir missing: {a if not a.exists() else b}')
        return 1
    ra, rb = load_job(a), load_job(b)
    if not ra or not rb:
        print('ERROR no trial results found in one of the job dirs')
        return 1
    problems = []
    for task in sorted(set(ra) | set(rb)):
        if task not in ra:
            problems.append(f'{task}: missing from first run')
        elif task not in rb:
            problems.append(f'{task}: missing from second run')
        elif ra[task] != rb[task]:
            problems.append(f'{task}: reward differs {ra[task]} vs {rb[task]}')
    print(f'run_a_tasks={len(ra)} run_b_tasks={len(rb)} problems={len(problems)}')
    for p in problems:
        print('ERROR', p)
    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--compare-jobs', nargs=2, metavar=('JOB_A', 'JOB_B'))
    args = ap.parse_args()
    if args.compare_jobs:
        return compare_jobs(Path(args.compare_jobs[0]), Path(args.compare_jobs[1]))
    return content_freeze()


if __name__ == '__main__':
    sys.exit(main())
