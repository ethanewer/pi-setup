/* low-bit round keys (8 bits each) baked at build time */
#ifndef YK0
#define YK0 0x11
#endif
#ifndef YK1
#define YK1 0x22
#endif
static unsigned int f(unsigned int x, unsigned int k){ return SBOX[(x^k)&0xff]; }
static unsigned int enc16(unsigned int P){
    unsigned int L=(P>>8)&0xff, R=P&0xff;
    unsigned int L1,R1,L2,R2;
    L1=R; R1=L ^ f(R,YK0);
    L2=R1; R2=L1 ^ f(R1,YK1);
    return (L2<<8)|R2;
}
int main(void){
    char line[64];
    while(fgets(line,sizeof line,stdin)){
        unsigned int P=(unsigned int)strtoul(line,NULL,16);
        printf("%04x\n", enc16(P));
    }
    return 0;
}
