def elf64_x86_64():
    eh = bytearray(64)
    eh[0:4] = b'\x7fELF'
    eh[4] = 2                    # ELFCLASS64
    eh[5] = 1                    # LSB
    eh[6] = 1
    struct.pack_into('<H', eh, 16, 2)    # ET_EXEC
    struct.pack_into('<H', eh, 18, 62)   # EM_X86_64
    struct.pack_into('<I', eh, 20, 1)
    struct.pack_into('<I', eh, 32, 64)   # e_phoff
    struct.pack_into('<H', eh, 52, 64)   # e_ehsize
    struct.pack_into('<H', eh, 54, 56)   # e_phentsize
    struct.pack_into('<H', eh, 56, 1)    # e_phnum
    ph = bytearray(56)
    struct.pack_into('<I', ph, 0, 1)     # PT_LOAD
    struct.pack_into('<I', ph, 4, 0)
    struct.pack_into('<I', ph, 24, 5)    # R+X
    struct.pack_into('<I', ph, 32, 0x1000)
    return bytes(eh) + bytes(ph)


