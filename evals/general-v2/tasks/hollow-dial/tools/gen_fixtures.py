BASE = 0x00400000          # guest load base (vaddr of the single PT_LOAD)
HDRLEN = 52 + 32           # ELF header + program header byte count

REG = {
    'zero': 0, 'at': 1, 'v0': 2, 'v1': 3, 'a0': 4, 'a1': 5, 'a2': 6, 'a3': 7,
    't0': 8, 't1': 9, 't2': 10, 't3': 11, 't4': 12, 't5': 13, 't6': 14, 't7': 15,
    's0': 16, 's1': 17, 's2': 18, 's3': 19, 's4': 20, 's5': 21, 's6': 22, 's7': 23,
    't8': 24, 't9': 25, 'k0': 26, 'k1': 27, 'gp': 28, 'sp': 29, 'fp': 30, 'ra': 31,
}


def r_type(funct, rs=0, rt=0, rd=0, shamt=0):
    return ((funct & 0x3f) | ((shamt & 0x1f) << 6) | ((rd & 0x1f) << 11)
            | ((rt & 0x1f) << 16) | ((rs & 0x1f) << 21))


def i_type(op, rs, rt, imm):
    return ((op & 0x3f) << 26) | ((rs & 0x1f) << 21) | ((rt & 0x1f) << 16) | (imm & 0xffff)


def regimm(rs, rt, imm):
    return (1 << 26) | ((rs & 0x1f) << 21) | ((rt & 0x1f) << 16) | (imm & 0xffff)


def _reg(s):
    if s.startswith('$'):
        s = s[1:]
    if s in REG:
        return REG[s]
    return int(s)


def _esc_bytes(s):
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            out.append({'n': 10, 't': 9, 'r': 13, '0': 0, '\\': 92}.get(n, ord(n)))
            i += 2
        else:
            out.append(ord(c))
            i += 1
    return bytes(out)


def assemble(prog_text):
    """Assemble a small MIPS program. Returns (code_bytes, data_bytes).

    Supported syntax (one instruction per line, '#' comments):
      label:                     define a label (text or data depending on section)
      op operand, operand, ...   instruction (operands separated by ',' or space)
      .word 0x...                emit a raw 4-byte word in the text section
      dbytes "text"              emit bytes into the data section (from here on data)
    """
    units = []          # ('label', name, section) | ('instr', op, ops) | ('raw', val) | ('data', bytes)
    section = 'code'
    for raw in prog_text.splitlines():
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        if line == '.data' or line == '.text':
            section = 'data' if line == '.data' else 'code'
            continue
        m = re.match(r'([A-Za-z_][A-Za-z0-9_]*):[ \t]*(.*)$', line)
        if m and (not m.group(2) or m.group(2).startswith('dbytes') or m.group(2).startswith('.word')):
            units.append(('label', m.group(1), section))
            line = m.group(2).strip()
            if not line:
                continue
        if line.startswith('dbytes '):
            payload = line[len('dbytes '):].strip()
            if payload.startswith('"') and payload.endswith('"'):
                payload = payload[1:-1]
            units.append(('data', _esc_bytes(payload), 'data'))
            section = 'data'
            continue
        if line.startswith('.word '):
            val = int(line[len('.word '):].strip(), 0)
            units.append(('raw', val, section))
            continue
        toks = line.replace(',', ' ').split()
        if toks[0].endswith(':') and len(toks) >= 2:
            units.append(('label', toks[0][:-1], section))
            toks = toks[1:]
        units.append(('instr', toks[0], toks[1:], section))

    # split into code / data units
    code_units = []
    data_units = []
    for u in units:
        if u[-1] == 'data':
            data_units.append(u)
        else:
            code_units.append(u)

    def unit_size(u):
        if u[0] == 'instr' and u[1] == 'la':
            return 2
        if u[0] in ('instr', 'raw'):
            return 1
        return 0

    n_instr = sum(unit_size(u) for u in code_units)
    data_base = BASE + 4 * n_instr

    # pass 1: assign addresses to labels
    symbols = {}
    off = 0
    for u in code_units:
        if u[0] == 'label':
            symbols[u[1]] = BASE + 4 * off
        else:
            off += unit_size(u)
    # first data label implicitly points to the start of data
    doff = 0
    for u in data_units:
        if u[0] == 'label':
            symbols[u[1]] = data_base + doff
        elif u[0] == 'data':
            doff += len(u[1])

    def immval(s):
        if s in symbols:
            return symbols[s]
        return int(s, 0)

    def enc(op, ops, addr):
        n = op.lower()
        if n == 'la':
            rd = _reg(ops[0]); target = immval(ops[1])
            return [i_type(15, 0, rd, (target >> 16) & 0xffff),
                    i_type(13, rd, rd, target & 0xffff)]
        if n == 'li':
            rd = _reg(ops[0]); v = immval(ops[1])
            if -32768 <= v <= 32767:
                return [i_type(9, 0, rd, v)]
            return [i_type(15, 0, rd, (v >> 16) & 0xffff),
                    i_type(13, rd, rd, v & 0xffff)]
        if n == 'nop':
            return [r_type(0, 0, 0, 0, 0)]
        if n in ('addu', 'subu', 'and', 'or', 'xor', 'nor', 'slt', 'sltu'):
            rd = _reg(ops[0]); rs = _reg(ops[1]); rt = _reg(ops[2])
            f = {'addu': 0x21, 'subu': 0x23, 'and': 0x24, 'or': 0x25,
                 'xor': 0x26, 'nor': 0x27, 'slt': 0x2a, 'sltu': 0x2b}[n]
            return [r_type(f, rs, rt, rd)]
        if n in ('sll', 'srl', 'sra'):
            rd = _reg(ops[0]); rt = _reg(ops[1]); sh = int(ops[2])
            f = {'sll': 0x00, 'srl': 0x02, 'sra': 0x03}[n]
            return [r_type(f, 0, rt, rd, sh)]
        if n in ('addi', 'addiu', 'slti', 'sltiu', 'andi', 'ori', 'xori'):
            rt = _reg(ops[0]); rs = _reg(ops[1]); imm = immval(ops[2])
            opc = {'addi': 8, 'addiu': 9, 'slti': 10, 'sltiu': 11,
                   'andi': 12, 'ori': 13, 'xori': 14}[n]
            return [i_type(opc, rs, rt, imm)]
        if n == 'lui':
            rt = _reg(ops[0]); imm = immval(ops[1])
            return [i_type(15, 0, rt, imm)]
        if n in ('lb', 'lbu', 'lw', 'lhu', 'sb', 'sh', 'sw'):
            rt = _reg(ops[0]); m = ops[1]
            if '(' in m:
                inner = m.split('(')[0]
                base = m.split('(')[1].rstrip(')')
            else:
                inner, base = '0', m
            rs = _reg(base); off_imm = immval(inner) if inner else 0
            opc = {'lb': 0x20, 'lbu': 0x24, 'lw': 0x23, 'lhu': 0x25,
                   'sb': 0x28, 'sh': 0x29, 'sw': 0x2b}[n]
            return [i_type(opc, rs, rt, off_imm)]
        if n in ('beq', 'bne'):
            rs = _reg(ops[0]); rt = _reg(ops[1]); target = immval(ops[2])
            imm = (target - (addr + 4)) >> 2
            if not (-32768 <= imm <= 32767):
                raise ValueError('branch out of range at %s' % n)
            return [i_type(4 if n == 'beq' else 5, rs, rt, imm)]
        if n in ('bgez', 'bltz'):
            rs = _reg(ops[0]); target = immval(ops[1])
            imm = (target - (addr + 4)) >> 2
            return [regimm(rs, 1 if n == 'bgez' else 0, imm)]
        if n in ('blez', 'bgtz'):
            rs = _reg(ops[0]); target = immval(ops[1])
            imm = (target - (addr + 4)) >> 2
            return [i_type(6 if n == 'blez' else 7, rs, 0, imm)]
        if n in ('j', 'jal'):
            target = immval(ops[0])
            return [((3 if n == 'jal' else 2) << 26) | ((target >> 2) & 0x03ffffff)]
        if n == 'jr':
            return [r_type(0x08, _reg(ops[0]), 0, 0, 0)]
        if n == 'syscall':
            return [r_type(0x0c)]
        raise ValueError('unknown mnemonic: %s' % n)

    code = bytearray()
    for u in code_units:
        if u[0] == 'raw':
            code += struct.pack('<I', u[1])
        elif u[0] == 'instr':
            for w in enc(u[1], u[2], BASE + len(code)):
                code += struct.pack('<I', w)

    data = bytearray()
    for u in data_units:
        if u[0] == 'data':
            data += u[1]
    return bytes(code), bytes(data)


def elf32_mips(code, data):
    """Emit a minimal 32-bit little-endian MIPS ELF executable (ET_EXEC, EM_MIPS)."""
    off = 52 + 32
    total = len(code) + len(data)
    eh = bytearray(52)
    eh[0:4] = b'\x7fELF'
    eh[4] = 1          # ELFCLASS32
    eh[5] = 1          # little-endian
    eh[6] = 1
    struct.pack_into('<H', eh, 16, 2)              # ET_EXEC
    struct.pack_into('<H', eh, 18, 8)              # EM_MIPS
    struct.pack_into('<I', eh, 20, 1)              # version
    struct.pack_into('<I', eh, 24, BASE)  # e_entry
    struct.pack_into('<I', eh, 28, 52)             # e_phoff
    struct.pack_into('<I', eh, 32, 0)              # e_shoff
    struct.pack_into('<I', eh, 36, 0)              # e_flags
    struct.pack_into('<H', eh, 40, 52)             # e_ehsize
    struct.pack_into('<H', eh, 42, 32)             # e_phentsize
    struct.pack_into('<H', eh, 44, 1)              # e_phnum
    ph = bytearray(32)
    struct.pack_into('<I', ph, 0, 1)               # PT_LOAD
    struct.pack_into('<I', ph, 4, off)
    struct.pack_into('<I', ph, 8, BASE)
    struct.pack_into('<I', ph, 12, BASE)
    struct.pack_into('<I', ph, 16, len(code)+len(data))  # p_filesz
    struct.pack_into('<I', ph, 20, len(code)+len(data))  # p_memsz
    struct.pack_into('<I', ph, 24, 7)              # PF_R|PF_W|PF_X
    struct.pack_into('<I', ph, 28, 4)
    return bytes(eh) + bytes(ph) + code + data


