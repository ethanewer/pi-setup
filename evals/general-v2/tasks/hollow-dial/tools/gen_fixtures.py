AOUT_MAGICS = (0x0107, 0x0108, 0x010B, 0x00CC)


def pdp11_aout(magic, code_words, data_bytes=b''):
    """Build a legacy PDP-11 a.out image: 16-byte header + text + data.

    The text holds plausible PDP-11 machine words (never executed here); the
    header magic is the classification signal.
    """
    text = b''.join(struct.pack('<H', w) for w in code_words)
    hdr = bytearray(16)
    struct.pack_into('<H', hdr, 0, magic)   # magic (OMAGIC/NMAGIC/...)
    struct.pack_into('<H', hdr, 2, len(text))       # tsize (bytes)
    struct.pack_into('<H', hdr, 4, len(data_bytes))  # dsize
    struct.pack_into('<H', hdr, 6, 0)               # bsize
    struct.pack_into('<H', hdr, 8, 0)               # ssize
    struct.pack_into('<H', hdr, 10, 0)              # entry offset
    struct.pack_into('<H', hdr, 12, 0)              # pad
    struct.pack_into('<H', hdr, 14, 0)              # flags
    return bytes(hdr) + text + data_bytes


