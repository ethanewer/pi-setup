"""Harbor Gasket import check -- run with the task venv's interpreter:

    /app/venv/bin/python /app/kit/import_check.py > /app/import-check.txt

Prints a deterministic, byte-stable report that proves the swellkit
framework (and its helper submodules and compiled C core) are importable and
functional inside /app/venv. Do not edit this file.
"""

_SAMPLE = (
    "# Halcyon Reach tide table\n"
    "\n"
    "M2,1.2,12.4206012,0\n"
    "S2,0.5,12.0,30.0\n"
    "K1,0.3,23.934472,120.0\n"
)


def main():
    import swellkit
    from swellkit import diagnostics, grid
    import swellkit._core as core  # compiled C core must exist

    h12 = swellkit.height_hours(12.0, _SAMPLE)
    f0 = swellkit.forecast_file("/app/data/constituents.csv", 0.0)
    rm = diagnostics.rms_amplitude([1.0, -3.0, 4.0])
    ms = diagnostics.mean_slice([10.0, 20.0, 30.0, 40.0], 1, 3)
    km = grid.haversine_km(-122.42, 37.77, -73.99, 40.71)
    cc = core.rms([-4.0, 4.0])

    print("HARBOR_GASKET_IMPORT_CHECK framework=swellkit version=%s core_ok=yes helpers=ok" % swellkit.__version__)
    print("height_hours(12.0)=%.9f forecast_file(0.0)=%.9f" % (h12, f0))
    print("rms_amplitude=%.12f mean_slice=%.12f" % (rm, ms))
    print("haversine_km=%.9f core_rms=%.12f" % (km, cc))


if __name__ == "__main__":
    main()
